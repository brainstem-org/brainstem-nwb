"""Render the mapping specification and the warning codes as Markdown (docs/mapping-spec.md, docs/warnings.md)."""

from __future__ import annotations

from collections import defaultdict

from .._version import KNOWN_EXPORT_MINOR, MAPPING_VERSION, SUPPORTED_DATA_MODELS, SUPPORTED_EXPORT_MAJOR
from ..manifest.warnings import CODES
from ..store.inventory import DROPPED_FIELDS
from .registry import MANIFEST_ONLY, RULES, STRUCTURAL, _load_mappers

_SECTION_ORDER = ["NWBFile", "Configuration", "Subject", "Devices", "Intervals", "Manifest"]


def _cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ")


def render_mapping_spec() -> str:
    _load_mappers()
    lines = [
        "# BrainSTEM to NWB mapping specification",
        "",
        "<!-- Generated by `brainstem-nwb mapping` (scripts/generate_docs.py); do not edit by hand. -->",
        "",
        f"Mapping version **{MAPPING_VERSION}**. BrainSTEM data model generation "
        f"{', '.join(f'`{m}`' for m in SUPPORTED_DATA_MODELS)} (read from the server at run time), project export "
        f"format {SUPPORTED_EXPORT_MAJOR}.{KNOWN_EXPORT_MINOR}.",
        "",
        "Each row is one rule. *Sources* are BrainSTEM fields as `app.model.field` (model field names, as in the "
        "project export). Values are written as stored; units are converted only where the table says so. "
        "Nothing is written when a source is empty unless *When missing* says otherwise, and every gap is "
        "recorded in the conversion manifest with its state (`present`, `missing`, `unknown`, "
        "`not_applicable`, `not_exported`).",
        "",
    ]
    by_section: dict[str, list] = defaultdict(list)
    for rule in RULES.values():
        by_section[rule.section].append(rule)
    for section in sorted(by_section, key=lambda s: _SECTION_ORDER.index(s) if s in _SECTION_ORDER else 99):
        lines += [f"## {section}", "",
                  "| Rule | NWB destination | Sources | Transformation | Units | Condition | When missing |",
                  "|---|---|---|---|---|---|---|"]
        for rule in sorted(by_section[section], key=lambda r: r.id):
            sources = "<br>".join(f"`{s}`" for s in rule.sources) or "—"
            lines.append(f"| `{rule.id}` | {_cell(rule.destination)} | {sources} | {_cell(rule.transform)} | "
                         f"{_cell(rule.units) or '—'} | {_cell(rule.condition)} | {_cell(rule.missing)} |")
        lines.append("")

    lines += [
        "## Fields used only to link records",
        "",
        "These fields decide which records belong to a session and subject; their values (BrainSTEM ids) are kept "
        "in the manifest.",
        "",
        "| Record type | Fields |",
        "|---|---|",
    ]
    for label in sorted(STRUCTURAL):
        if STRUCTURAL[label]:
            lines.append(f"| `{label}` | {', '.join(f'`{f}`' for f in sorted(STRUCTURAL[label]))} |")
    lines += [
        "",
        "## Kept in the manifest only",
        "",
        "These fields have no NWB destination in metadata-only files. They are copied to the manifest unchanged "
        "and, when they hold a value, listed in each file's notes. `*` means every field of the record type. "
        "`created_at` and `updated_at` of every record are kept in the manifest as well.",
        "",
        "| Record type | Field | Reason |",
        "|---|---|---|",
    ]
    for label in sorted(MANIFEST_ONLY):
        for field_name, reason in sorted(MANIFEST_ONLY[label].items()):
            lines.append(f"| `{label}` | `{field_name}` | {_cell(reason)} |")
    lines += [
        "",
        "## Dropped",
        "",
        f"{', '.join(f'`{f}`' for f in sorted(DROPPED_FIELDS))}: the record's creator (a user id) and server "
        "bookkeeping. They are not copied to the manifest.",
        "",
    ]
    return "\n".join(lines)


def render_warnings() -> str:
    lines = [
        "# Warning codes",
        "",
        "<!-- Generated by `brainstem-nwb mapping --warnings` (scripts/generate_docs.py); do not edit by hand. -->",
        "",
        "Every warning in a manifest has one of these codes. Severity: `error` means the unit cannot be produced or "
        "would be wrong; `warning` means information was lost or a placeholder was used; `info` is an expected gap.",
        "",
        "| Code | Severity | Meaning |",
        "|---|---|---|",
    ]
    for code in sorted(CODES):
        entry = CODES[code]
        lines.append(f"| `{code}` | {entry.severity} | {_cell(entry.description)} |")
    return "\n".join(lines) + "\n"
